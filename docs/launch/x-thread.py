URL = re.compile(r"(https?://\S+|\b[a-z0-9.-]+\.(?:org|com|dev|md)/\S*)")


def weighted(text: str) -> int:
    n, last = 0, 0
    for m in URL.finditer(text):
        n += weighted_plain(text[last:m.start()]) + 23
        last = m.end()
    return n + weighted_plain(text[last:])


def weighted_plain(s: str) -> int:
    w = 0
    for ch in s:
        c = ord(ch)
        light = c <= 4351 or 8192 <= c <= 8205 or 8208 <= c <= 8223 or 8242 <= c <= 8247
        w += 1 if light else 2
    return w


